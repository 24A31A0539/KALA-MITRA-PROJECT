"""
================================================================================
KALA-MITRA PAYMENT MODULE — PAYMENT API SCHEMAS
================================================================================
File: payment/schemas/payment_schemas.py
Description:
    Request and Response data contracts for payment operations:
    1. Create Payment Order
    2. Verify Payment Signature
    3. Query Payment Status
    4. Issue Refund
    5. Handle Webhook Response
================================================================================
"""
from decimal import Decimal
from datetime import datetime
from typing import Optional, Dict, Any
from pydantic import BaseModel, Field, ConfigDict
from payment.interface.payment_interface import PaymentStatus, PaymentProvider
from payment.schemas.order_schemas import OrderStatus, to_camel


class PaymentBase(BaseModel):
    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
        from_attributes=True
    )


# --- 1. Create Payment Order ---
class PaymentOrderCreateRequest(PaymentBase):
    order_id: str = Field(..., description="KALA-MITRA Order ID to initiate checkout for")
    notes: Optional[Dict[str, str]] = Field(default=None, description="Optional metadata or customer details")


class PaymentOrderCreateResponse(PaymentBase):
    order_id: str = Field(..., description="KALA-MITRA Order ID")
    payment_order_id: str = Field(..., description="Gateway Order ID generated by Razorpay/Mock (e.g. order_xxx)")
    amount: Decimal = Field(..., description="Total payable amount in standard currency units (INR)")
    currency: str = Field("INR", description="ISO 4217 Currency code")
    provider: PaymentProvider = Field(..., description="Active payment provider name")
    public_key: Optional[str] = Field(None, description="Client publishable key for Frontend SDK (safe to expose)")
    checkout_payload: Dict[str, Any] = Field(
        default_factory=dict,
        description="Gateway-specific options dictionary passed directly to client checkout SDK"
    )


# --- 2. Verify Payment Signature ---
class PaymentVerifyRequest(PaymentBase):
    order_id: str = Field(..., description="KALA-MITRA Order ID")
    payment_order_id: str = Field(..., description="Gateway Order ID created on server")
    payment_id: str = Field(..., description="Gateway Transaction/Payment ID returned by checkout SDK (e.g. pay_xxx)")
    signature: str = Field(..., description="Cryptographic HMAC-SHA256 signature returned by checkout SDK")
    payment_method: Optional[str] = Field(None, description="Payment method used (e.g. upi, card, netbanking)")


class PaymentVerifyResponse(PaymentBase):
    order_id: str = Field(..., description="KALA-MITRA Order ID")
    payment_status: PaymentStatus = Field(..., description="Verified financial payment status (PAID/FAILED)")
    order_status: OrderStatus = Field(..., description="Updated order fulfillment status (CONFIRMED)")
    verified: bool = Field(..., description="Whether cryptographic signature verified successfully")
    payment_transaction_id: Optional[str] = Field(None, description="Recorded transaction identifier")
    message: str = Field(..., description="Status summary message")


# --- 3. Payment Status Lookup ---
class PaymentStatusResponse(PaymentBase):
    order_id: str = Field(..., description="KALA-MITRA Order ID")
    payment_order_id: Optional[str] = Field(None, description="Gateway Order ID")
    payment_transaction_id: Optional[str] = Field(None, description="Gateway Transaction ID")
    payment_status: PaymentStatus = Field(..., description="Financial settlement state")
    order_status: OrderStatus = Field(..., description="Fulfillment state")
    amount: Decimal = Field(..., description="Order total amount")
    currency: str = Field(..., description="Currency code")
    provider: PaymentProvider = Field(..., description="Payment provider")
    created_at: datetime = Field(..., description="Order creation timestamp")
    updated_at: datetime = Field(..., description="Last update timestamp")


# --- 4. Refund ---
class RefundRequest(PaymentBase):
    order_id: str = Field(..., description="KALA-MITRA Order ID to refund")
    amount: Optional[Decimal] = Field(None, description="Optional partial refund amount. If omitted, full refund.")
    reason: Optional[str] = Field(None, description="Justification reason for issuing refund")


class RefundResponse(PaymentBase):
    order_id: str = Field(..., description="KALA-MITRA Order ID")
    refund_id: Optional[str] = Field(None, description="Gateway Refund identifier")
    payment_status: PaymentStatus = Field(..., description="Updated payment status (REFUNDED)")
    amount_refunded: Decimal = Field(..., description="Total amount refunded")
    success: bool = Field(..., description="Whether refund succeeded")
    message: str = Field(..., description="Status summary")


# --- 5. Webhook ---
class WebhookResponse(BaseModel):
    success: bool
    message: str
    event_id: Optional[str] = None
    status: str
